// Pull the page (styles, markup, script) from the Python project's template,
// which remains the reference for the visualisation.
//
//   node scripts/sync-template.mjs [path/to/template.html]
//
// Writes src/content/page.css, src/content/page.html and, for comparison only,
// src/page/template-script.js (the page's script as the Python version ships
// it; src/page/page.js is the version adapted to the plugin).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2] || path.join(ROOT, "..", "zotero-as-your-archive", "src", "zotero_archive", "template.html");
const html = readFileSync(source, "utf8");

const START = "<!-- zotero-archive:fragment -->";
const END = "<!-- /zotero-archive:fragment -->";
const fragment = html.slice(html.indexOf(START) + START.length, html.indexOf(END));
const style = fragment.match(/<style>([\s\S]*?)<\/style>/)[1].trim();
const article = fragment.match(/<article[\s\S]*?<\/article>/)[0].trim();
const scripts = [...fragment.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const script = scripts[scripts.length - 1].trim();

const note = (comment) => `${comment} Generated by scripts/sync-template.mjs from the Python project's template.html: edit there.`;
mkdirSync(path.join(ROOT, "src", "content"), { recursive: true });
mkdirSync(path.join(ROOT, "src", "page"), { recursive: true });
writeFileSync(path.join(ROOT, "src", "content", "page.css"), `/* ${note("")} */\n${style}\n`);
writeFileSync(path.join(ROOT, "src", "content", "page.html"), `<!-- ${note("")} -->\n${article}\n`);
writeFileSync(path.join(ROOT, "src", "page", "template-script.js"), `// ${note("")}\n${script}\n`);
console.log(`page.css: ${style.length} chars, page.html: ${article.length} chars, script: ${script.length} chars`);
